    fun translate(context: Context, value: String): String {
        val saved = runCatching {
            context.getSharedPreferences("deadsmile-ui", Context.MODE_PRIVATE).getString("app_language", "").orEmpty()
        }.getOrDefault("")
        val systemLanguage = runCatching { context.resources.configuration.locales[0]?.language }.getOrNull()
            ?: Locale.getDefault().language
        val language = saved.ifBlank { systemLanguage }
        return translate(language, value)
    }

    internal fun translate(language: String, value: String): String {
        val table = when (language.lowercase(Locale.ROOT)) {
            "en" -> english
            "es" -> spanish
            else -> return value
        }
        return table[value] ?: when {
            value.startsWith("Desenvolvido por ") ->
                table.getValue("Desenvolvido por ") + value.removePrefix("Desenvolvido por ")
            value.startsWith("Publicado por ") ->
                table.getValue("Publicado por ") + value.removePrefix("Publicado por ")
            value.startsWith("Anunciado. Lançamento previsto em ") ->
                table.getValue("Anunciado. Lançamento previsto em ") + value.removePrefix("Anunciado. Lançamento previsto em ")
            value.startsWith("Lançamento previsto em ") ->
                table.getValue("Lançamento previsto em ") + value.removePrefix("Lançamento previsto em ")
            value.startsWith("Data prevista: ") ->
                table.getValue("Data prevista: ") + value.removePrefix("Data prevista: ")
            value.startsWith("Plataformas: ") ->
